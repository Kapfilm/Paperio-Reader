"""Rasterize Barlow Condensed clock numerals at their final display size."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/fonts/flip-clock/BarlowCondensed-ExtraBold.ttf"
WIDTH, HEIGHT, OVERSAMPLE = 88, 180, 4
size = 320
while True:
    font = ImageFont.truetype(str(SOURCE), size * OVERSAMPLE)
    boxes = [font.getbbox(str(d)) for d in range(10)]
    if max(b[3] - b[1] for b in boxes) <= (HEIGHT - 4) * OVERSAMPLE:
        break
    size -= 1

# Use a shared horizontal compression and fixed advance for the narrow,
# tall numerals on a mechanical flip-clock card.
source_width = max(b[2] - b[0] for b in boxes) + 4 * OVERSAMPLE
glyphs = []
for digit, box in enumerate(boxes):
    glyph = Image.new("L", (source_width, HEIGHT * OVERSAMPLE), 255)
    x = (glyph.width - (box[2] - box[0])) // 2 - box[0]
    y = (glyph.height - (box[3] - box[1])) // 2 - box[1]
    ImageDraw.Draw(glyph).text((x, y), str(digit), font=font, fill=0)
    glyph = glyph.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    glyphs.append(glyph.point(lambda value: 255 if value >= 128 else 0).convert("1"))

header = ["#pragma once", "#include <cstdint>", "", "// Barlow Condensed ExtraBold, SIL Open Font License.",
          "// Generated by scripts/generate_flip_clock_digits.py at native pixel size.",
          f"inline constexpr int FLIP_DIGIT_WIDTH = {WIDTH};",
          f"inline constexpr int FLIP_DIGIT_HEIGHT = {HEIGHT};",
          f"inline constexpr uint8_t FLIP_DIGITS[10][{WIDTH * HEIGHT // 8}] = {{"]
for glyph in glyphs:
    data = glyph.tobytes()
    assert len(data) == WIDTH * HEIGHT // 8
    header.append("  {")
    header.extend("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + "," for i in range(0, len(data), 16))
    header.append("  },")
header.append("};")
(ROOT / "src/images/FlipClockDigits.h").write_text("\n".join(header) + "\n")

preview = Image.new("L", (800, 480), 255)
draw = ImageDraw.Draw(preview)
left, top, card_width, card_height, gap = 154, 97, 232, 249, 22
for card, text in enumerate(("08", "19")):
    x = left + card * (card_width + gap)
    draw.rounded_rectangle((x+2, top+5, x+card_width+2, top+card_height+5), radius=20, fill=0)
    draw.rounded_rectangle((x, top, x+card_width-1, top+card_height-1), radius=20, fill=255, outline=0, width=2)
    for i, char in enumerate(text):
        preview.paste(glyphs[int(char)], (x+(card_width-2*WIDTH-8)//2+i*(WIDTH+8), top+(card_height-HEIGHT)//2))
    draw.line((x+2, top+card_height//2, x+card_width-3, top+card_height//2), fill=0)
preview.save("/private/tmp/paperio-flip-clock-font-preview.png")
