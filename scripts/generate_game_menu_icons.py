#!/usr/bin/env python3
"""Generate crisp 1-bit game icons with supersampled curves (requires Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import argparse

parser = argparse.ArgumentParser()
parser.add_argument('--font', default='/System/Library/Fonts/Supplemental/Arial Bold.ttf')
args = parser.parse_args()
SIZE, SCALE = 88, 8

def icon(k):
    im = Image.new('L', (SIZE*SCALE, SIZE*SCALE), 255)
    d = ImageDraw.Draw(im)
    def box(coords, radius=0, width=2.5, fill=None):
        coords = tuple(round(v*SCALE) for v in coords)
        if radius:
            d.rounded_rectangle(coords, radius=round(radius*SCALE), outline=0, fill=fill, width=round(width*SCALE))
        else:
            d.rectangle(coords, outline=0, fill=fill, width=round(width*SCALE))
    def line(coords, width=2.5, color=0):
        d.line(tuple(round(v*SCALE) for v in coords), fill=color, width=round(width*SCALE), joint='curve')
    def text(x,y,t,n):
        d.text((round(x*SCALE),round(y*SCALE)), t, font=ImageFont.truetype(args.font,round(n*SCALE)), fill=0, anchor='mm')
    box((2,2,85,85),radius=14,width=3)
    if k==0:
        for v in (17,35,53,71):
            line((v,17,v,71)); line((17,v,71,v))
        for x,y,t in [(26,26,'1'),(44,44,'3'),(62,26,'2'),(26,62,'4'),(62,62,'1')]: text(x,y,t,15)
    elif k==1:
        for x,y in [(18,18),(36,18),(54,18),(18,36),(18,54)]: box((x,y,x+15,y+15))
        box((40,42,65,67),width=3)
        line((42,44,63,65)); line((63,44,42,65))
    elif k==2:
        for v in (16,35,54,73):
            line((v,16,v,73)); line((16,v,73,v))
        for x,y in [(16,16),(35,16),(16,35)]:
            box((x,y,x+19,y+19),fill=0)
            line((x+2,y+2,x+17,y+17),width=2,color=255)
        for x,y,t in [(44,44,'4'),(63,44,'2'),(44,63,'1'),(63,63,'3')]: text(x,y,t,15)
    elif k==3:
        line((19,65,51,65),3); line((25,65,25,18,57,18,57,27),3)
        d.ellipse(tuple(round(v*SCALE) for v in (51,27,63,39)),outline=0,width=round(2.5*SCALE))
        for coords in [(57,39,57,53),(47,42,57,47,67,42),(57,53,49,62),(57,53,65,62)]: line(coords)
        for x in (25,41,57): line((x,75,x+10,75))
    elif k==4:
        for i,t in enumerate('12345678'):
            x=16+(i%3)*19; y=16+(i//3)*19
            box((x,y,x+17,y+17),radius=3,width=2.5); text(x+8.5,y+8.5,t,12)
    elif k==5:
        # Peg Solitaire: the traditional cross board with one empty central hole.
        for row in range(5):
            for col in range(5):
                if row not in (1,2,3) and col not in (1,2,3): continue
                if row in (0,4) and col != 2: continue
                if col in (0,4) and row != 2: continue
                x=22+col*11; y=22+row*11
                d.ellipse(tuple(round(v*SCALE) for v in (x-3.3,y-3.3,x+3.3,y+3.3)),
                          fill=255 if row==2 and col==2 else 0,
                          outline=0,width=round(1.8*SCALE))
    elif k==6:
        # Delve hero from Omer Faruk Inel's MIT-licensed sprites.lua.
        # Matches the pixel knight and raised sword in the supplied reference.
        hero = (0x03c4,0x07e4,0x0424,0x05a4,0x07e4,0x03ce,0x0ff8,0x1de0,
                0x17e0,0x17e0,0x35a0,0x07e0,0x0660,0x0660,0x0660,0x0e70)
        for y,bits in enumerate(hero):
            for x in range(16):
                if bits & (0x8000 >> x):
                    px=(12+x*4)*SCALE; py=(12+y*4)*SCALE
                    d.rectangle((px,py,px+4*SCALE-1,py+4*SCALE-1),fill=0)
    elif k==7:
        # Approved variant B: branching network on a tile grid.
        box((17,17,71,71),radius=4,width=2.5)
        for v in (35,53):
            line((v,18,v,70),1.5); line((18,v,70,v),1.5)
        line((26,26,44,26,44,44,62,44,62,62,44,62),3.5)
        line((26,26,26,62),3.5)
        for x,y in [(26,26),(26,62),(44,62)]:
            d.ellipse(tuple(round(v*SCALE) for v in (x-3,y-3,x+3,y+3)),fill=0)
        d.ellipse(tuple(round(v*SCALE) for v in (58,22,66,30)),fill=0)
        line((62,26,62,44),3.5)
    elif k==8:
        # Approved variant B: logic grid with affirmative and excluded pairs.
        for v in (20,36,52,68):
            line((v,20,v,68),2); line((20,v,68,v),2)
        for x,y in [(28,28),(44,44),(60,60)]: line((x-4,y,x-1,y+3,x+4,y-4),2.5)
        for x,y in [(44,28),(28,44),(60,44),(44,60)]:
            line((x-3,y-3,x+3,y+3),2); line((x+3,y-3,x-3,y+3),2)
    return im.resize((SIZE,SIZE),Image.Resampling.LANCZOS).point(lambda v:255 if v>=128 else 0).convert('1')

icons=[icon(k) for k in range(9)]
rows=[]
for im in icons:
    data=im.tobytes()
    rows.append('  {\n'+'\n'.join('    '+', '.join(f'0x{x:02x}' for x in data[i:i+22])+',' for i in range(0,len(data),22))+'\n  },')
root=Path(__file__).resolve().parents[1]
(root/'src/images/GameMenuIcons.h').write_text('#pragma once\n#include <cstdint>\n\n// Generated by scripts/generate_game_menu_icons.py. White = 1, MSB first.\n// 88 px is approximately 1 cm on X4 Classic. Curves rasterized at 8x resolution.\ninline constexpr int GAME_ICON_SIZE = 88;\ninline constexpr uint8_t GAME_MENU_ICONS[9][968] = {\n'+'\n'.join(rows)+'\n};\n')
preview=Image.new('1',(9*108,208),1)
for i,im in enumerate(icons):
    preview.paste(im,(i*108+10,8))
    from PIL import ImageOps
    preview.paste(ImageOps.invert(im.convert('L')).convert('1'),(i*108+10,112))
preview.save('/private/tmp/paperio-game-icons-refined.png')
