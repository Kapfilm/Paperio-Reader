#!/usr/bin/env python3
"""Generate crisp 1-bit game icons with supersampled curves (requires Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import argparse

parser = argparse.ArgumentParser()
parser.add_argument('--font', default='/System/Library/Fonts/Supplemental/Arial Bold.ttf')
args = parser.parse_args()
SIZE, SCALE = 88, 8

def icon(k):
    im = Image.new('L', (SIZE*SCALE, SIZE*SCALE), 255)
    d = ImageDraw.Draw(im)
    def box(coords, radius=0, width=2.5, fill=None):
        coords = tuple(round(v*SCALE) for v in coords)
        if radius:
            d.rounded_rectangle(coords, radius=round(radius*SCALE), outline=0, fill=fill, width=round(width*SCALE))
        else:
            d.rectangle(coords, outline=0, fill=fill, width=round(width*SCALE))
    def line(coords, width=2.5, color=0):
        d.line(tuple(round(v*SCALE) for v in coords), fill=color, width=round(width*SCALE), joint='curve')
    def text(x,y,t,n):
        d.text((round(x*SCALE),round(y*SCALE)), t, font=ImageFont.truetype(args.font,round(n*SCALE)), fill=0, anchor='mm')
    box((2,2,85,85),radius=14,width=3)
    if k==0:
        for v in (17,35,53,71):
            line((v,17,v,71)); line((17,v,71,v))
        for x,y,t in [(26,26,'1'),(44,44,'3'),(62,26,'2'),(26,62,'4'),(62,62,'1')]: text(x,y,t,15)
    elif k==1:
        for x,y in [(18,18),(36,18),(54,18),(18,36),(18,54)]: box((x,y,x+15,y+15))
        box((40,42,65,67),width=3)
        line((42,44,63,65)); line((63,44,42,65))
    elif k==2:
        for v in (16,35,54,73):
            line((v,16,v,73)); line((16,v,73,v))
        for x,y in [(16,16),(35,16),(16,35)]:
            box((x,y,x+19,y+19),fill=0)
            line((x+2,y+2,x+17,y+17),width=2,color=255)
        for x,y,t in [(44,44,'4'),(63,44,'2'),(44,63,'1'),(63,63,'3')]: text(x,y,t,15)
    elif k==3:
        line((19,65,51,65),3); line((25,65,25,18,57,18,57,27),3)
        d.ellipse(tuple(round(v*SCALE) for v in (51,27,63,39)),outline=0,width=round(2.5*SCALE))
        for coords in [(57,39,57,53),(47,42,57,47,67,42),(57,53,49,62),(57,53,65,62)]: line(coords)
        for x in (25,41,57): line((x,75,x+10,75))
    else:
        for i,t in enumerate('12345678'):
            x=16+(i%3)*19; y=16+(i//3)*19
            box((x,y,x+17,y+17),radius=3,width=2.5); text(x+8.5,y+8.5,t,12)
    return im.resize((SIZE,SIZE),Image.Resampling.LANCZOS).point(lambda v:255 if v>=128 else 0).convert('1')

icons=[icon(k) for k in range(5)]
rows=[]
for im in icons:
    data=im.tobytes()
    rows.append('  {\n'+'\n'.join('    '+', '.join(f'0x{x:02x}' for x in data[i:i+22])+',' for i in range(0,len(data),22))+'\n  },')
root=Path(__file__).resolve().parents[1]
(root/'src/images/GameMenuIcons.h').write_text('#pragma once\n#include <cstdint>\n\n// Generated by scripts/generate_game_menu_icons.py. White = 1, MSB first.\n// 88 px is approximately 1 cm on X4 Classic. Curves rasterized at 8x resolution.\ninline constexpr int GAME_ICON_SIZE = 88;\ninline constexpr uint8_t GAME_MENU_ICONS[5][968] = {\n'+'\n'.join(rows)+'\n};\n')
preview=Image.new('1',(5*108,208),1)
for i,im in enumerate(icons):
    preview.paste(im,(i*108+10,8))
    from PIL import ImageOps
    preview.paste(ImageOps.invert(im.convert('L')).convert('1'),(i*108+10,112))
preview.save('/private/tmp/paperio-game-icons-refined.png')
