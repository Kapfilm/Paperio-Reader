#!/usr/bin/env python3
"""Convert upstream MIT Lamplighter banks into packed flash bytes (no runtime generator)."""
import argparse,hashlib
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('source',type=Path);p.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'src/activities/games/lamplighter/LamplighterData.h');a=p.parse_args()
s=['#pragma once','#include <cstdint>','// Upstream MIT ©2026 Omer Faruk Inel; generated by scripts/convert_lamplighter_data.py.','namespace lamplighter::data {']
for label,n in [('easy',5),('medium',7),('hard',9)]:
 f=a.source/f'lamplighter-{label}.txt';raw=f.read_bytes();lines=raw.decode().splitlines();assert len(lines)==200
 s.append('// '+label+' SHA256 '+hashlib.sha256(raw).hexdigest())
 s.append(f'inline constexpr uint8_t {label}[200][{n*n+1}] = {{')
 for line in lines:
  assert len(line)==3+2*n*n and int(line[0])==n
  sol=[int(x,16) for x in line[1:1+n*n]];start=[int(x,16) for x in line[1+n*n:1+2*n*n]];src=int(line[-2:]);assert src<n*n
  for x,y in zip(sol,start):assert y in [((x<<r)|(x>>(4-r)))&15 for r in range(4)]
  s.append(' {'+','.join(str((x<<4)|y) for x,y in zip(sol,start))+','+str(src)+'},')
 s.append('};')
s.append('}')
a.output.write_text('\n'.join(s)+'\n')
