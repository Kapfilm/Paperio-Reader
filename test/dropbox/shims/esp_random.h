#pragma once
#include <cstddef>
#include <cstdint>
// RFC 7636 Appendix B verifier, decoded from base64url.
inline void esp_fill_random(void* out, size_t length) {
  static constexpr uint8_t bytes[32] = {0x74, 0x18, 0xdf, 0xb4, 0x97, 0x99, 0xe0, 0x25, 0x4f, 0xfa, 0x60,
                                        0x7d, 0xd8, 0xad, 0xbb, 0xba, 0x16, 0xd4, 0x25, 0x4d, 0x69, 0xd6,
                                        0xbf, 0xf0, 0x5b, 0x58, 0x05, 0x58, 0x53, 0x84, 0x8d, 0x79};
  for (size_t i = 0; i < length; ++i) static_cast<uint8_t*>(out)[i] = bytes[i % 32];
}
